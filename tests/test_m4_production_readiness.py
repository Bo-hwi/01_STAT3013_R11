@pytest.mark.parametrize("failure", ["write", "reload", "rename"])
def test_failed_transaction_is_detectable_and_never_finalized(tmp_path, synthetic_run, monkeypatch, failure):
    if failure == "write":
        original = artifacts._write_csv

        def fail_write(path, table):
            if path.name == "metrics.csv":
                raise OSError("synthetic disk failure")
            original(path, table)

        monkeypatch.setattr(artifacts, "_write_csv", fail_write)
    elif failure == "reload":
        monkeypatch.setattr(artifacts.pd, "read_csv", lambda *a, **k: (_ for _ in ()).throw(ValueError("synthetic corrupt CSV")))
    else:
        monkeypatch.setattr(Path, "rename", lambda *a, **k: (_ for _ in ()).throw(OSError("synthetic rename failure")))
    with pytest.raises((OSError, ValueError)):
        qp.save_run(*synthetic_run, root=tmp_path)
    _, final = artifacts.output_paths(tmp_path, "synthetic_test_only")
    assert not final.exists()
    assert artifacts.inspect_run(tmp_path, "synthetic_test_only")["status"] == "incomplete"
    with pytest.raises(FileExistsError):
        qp.save_run(*synthetic_run, root=tmp_path)


