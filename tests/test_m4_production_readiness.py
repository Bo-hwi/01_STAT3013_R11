def test_frozen_provenance_is_detached_and_detects_changed_inputs(tmp_path, synthetic_run):
    manifest = synthetic_run[2]["manifest"]
    assert manifest["provenance"]["effective_protocol_sha256"]
    verify_frozen_files(manifest["provenance"])
    evidence = tmp_path / "evidence.txt"
    evidence.write_text("before", encoding="utf-8")
    frozen = deepcopy(manifest["provenance"])
    frozen["input"] = {"file_sha256": {str(evidence): file_hash(evidence)}}
    evidence.write_text("after", encoding="utf-8")
    with pytest.raises(ValueError, match="Input evidence changed"):
        verify_frozen_files(frozen)
    frozen["input"] = {}
    frozen["file_sha256"] = {str(evidence): "not-the-original-digest"}
    with pytest.raises(ValueError, match="Code/config changed"):
        verify_frozen_files(frozen)


def test_specification_is_frozen_before_fit_and_detached(monkeypatch, features, contracts):
    protocol, ablation = deepcopy(contracts)
    freeze = qp.freeze_provenance
    builder = qp.build_quantile_pipeline
    state = {"frozen": False}

    def capture_freeze(*args):
        snapshot = freeze(*args)
        state["frozen"] = True
        return snapshot

    def fit_after_freeze(*args):
        assert state["frozen"]
        protocol["project"]["seed"] = 999  # Caller dict only, not a shared file.
        return builder(*args)

    monkeypatch.setattr(qp, "freeze_provenance", capture_freeze)
    monkeypatch.setattr(qp, "build_quantile_pipeline", fit_after_freeze)
    result = qp.run_direct_quantiles(features, protocol, ablation, "synthetic_freeze", [GRID[0]])
    assert result[2]["manifest"]["seed"] == contracts[0]["project"]["seed"]
    assert result[2]["manifest"]["contracts"]["protocol"]["project"]["seed"] != 999


def test_multi_fold_f1_f4_integration(features, contracts):
    protocol = qp.read_yaml(qp.ROOT / "configs/research_protocol.yaml")
    ablation = contracts[1]
    families = protocol["scope"]["deep_study_families"]
    dates = pd.date_range("2016-06-01", "2017-08-15")
    dates = dates[~((dates.month == 12) & (dates.day == 25))]
    raw = pd.MultiIndex.from_product([dates, [1, 52], families], names=qp.KEY).to_frame(index=False)
    raw["city"] = raw.store_nbr.map({1: "SYNTHETIC_A", 52: "SYNTHETIC_B"})
    raw["store_active"] = (~raw.store_nbr.eq(52) | raw.date.ge("2017-04-20")).astype(int)
    raw["sales"] = np.where(raw.store_active.eq(1), 10.5 + raw.date.dt.day, 0)
    raw["store_zero_day"] = raw.store_active.eq(0).astype(int)
    for column in FEATURES["calendar"]:
        raw[column] = 0
    raw["month"], raw["day_of_week"] = raw.date.dt.month, raw.date.dt.dayofweek
    data = prepare_features(raw, ready=False)
    for column in qp.CORE_WEATHER:
        data[column] = 1.
    data = add_scoring_mask(data, ablation["scoring_exclusions"])
    data = data.drop(columns=["excluded_closure", "excluded_post_reopening"])
    predictions, metrics, diagnostics = qp.run_direct_quantiles(data, protocol, ablation, "synthetic_four_folds", [GRID[0]])
    assert set(predictions.fold) == {"F1", "F2", "F3", "F4"}
    assert set(predictions.loc[predictions.store_nbr.eq("52"), "fold"]) == {"F4"}
    assert len(diagnostics["tuning"]) == 4 * 2 * 3
    assert len(diagnostics["manifest"]["scored_key_contract"]) == 8
    assert metrics.sample_size.gt(0).all()
