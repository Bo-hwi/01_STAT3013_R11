@pytest.mark.parametrize("fault", ["tau", "null", "missing_row", "mismatch", "crossing", "correction"])
def test_prediction_panel_rejects_incomplete_or_inconsistent_inputs(synthetic_run, fault):
    panel = synthetic_run[0].copy()
    if fault == "tau":
        panel = panel[panel.tau_key.ne(TAU_KEYS[2])]
    elif fault == "null":
        panel.loc[0, "city"] = None
    elif fault == "missing_row":
        key = panel.iloc[0]
        panel = panel[~(panel.config.eq("M3") & panel.date.eq(key.date)
                        & panel.store_nbr.eq(key.store_nbr) & panel.family.eq(key.family) & panel.split.eq(key.split))]
    elif fault == "mismatch":
        panel.loc[0, "y_true"] += 1
    elif fault == "crossing":
        panel.loc[0, "raw_crossing"] = not panel.loc[0, "raw_crossing"]
    else:
        panel.loc[0, "corrected_prediction"] += 1
    with pytest.raises(ValueError):
        qp.summarize_predictions(panel)


