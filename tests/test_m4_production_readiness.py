def test_production_preflight_verifies_available_evidence(delivery):
    root, path, protocol, ablation = delivery
    frame, report = production_preflight(path, protocol, ablation, root)
    assert not report["hard_failures"]
    assert report["warnings"] and report["unavailable"]
    assert report["file_sha256"][str(path.resolve())] == file_hash(path)
    assert len(report["fold_scored_counts"]) == 2
    assert len(frame) == pd.read_parquet(path).shape[0]


@pytest.mark.parametrize("fault", ["truncated", "missing_key", "null_city", "hash", "source_digest", "metadata", "weather", "scope", "reference", "grid_id"])
def test_production_contract_failures(delivery, fault):
    root, path, protocol, ablation = delivery
    frame = pd.read_parquet(path)
    if fault in ("truncated", "missing_key"):
        frame = frame.iloc[14:] if fault == "truncated" else frame.drop(index=100)
        frame.to_parquet(path, index=False)
    elif fault == "null_city":
        frame.loc[0, "city"] = None
        frame.to_parquet(path, index=False)
    elif fault == "hash":
        raw = root / "data/raw/favorita/train.csv"
        raw.write_text(raw.read_text() + '\n', encoding="utf-8")
    elif fault == "metadata":
        meta_path = path.with_suffix(".meta.json")
        meta = json.loads(meta_path.read_text())
        meta["n_rows"] += 1
        meta_path.write_text(json.dumps(meta), encoding="utf-8")
    elif fault == "source_digest":
        meta_path = path.parent / "curated_sales_weather.meta.json"
        meta = json.loads(meta_path.read_text())
        meta["source_sha256"]["train.csv"] = meta["source_sha256"]["stores.csv"]
        meta_path.write_text(json.dumps(meta), encoding="utf-8")
    elif fault == "grid_id":
        curated_path = path.parent / "curated_sales_weather.parquet"
        curated = pd.read_parquet(curated_path)
        curated["weather_grid_id"] = "wrong"
        curated.to_parquet(curated_path, index=False)
    elif fault == "weather":
        frame.loc[frame.date.eq("2016-09-05"), "precipitation_sum_lag1"] = -1
        frame.to_parquet(path, index=False)
    elif fault == "scope":
        protocol["scope"]["stores_expected"] = 54
    else:
        target = root / "results/tables"
        target.mkdir(parents=True)
        pd.DataFrame(dict(report_level=["fold"], fold=["F1"], n_scored=[1])).to_csv(target / "baselines_metrics.csv", index=False)
    with pytest.raises(ProductionPreflightError) as error:
        production_preflight(path, protocol, ablation, root)
    assert error.value.report["hard_failures"]


